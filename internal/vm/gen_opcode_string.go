//go:build ignore

// gen_opcode_string.go генерирует opcode_string.go: имя каждого опкода —
// первый токен его строчного комментария в opcode.go (напр. `// INDEX_SET ...`
// -> "INDEX_SET"). Запуск: go generate ./internal/vm/.
package main

import (
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	data, err := os.ReadFile("opcode.go")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	src := string(data)
	i := strings.Index(src, "\tOpHalt")
	if i < 0 {
		fmt.Fprintln(os.Stderr, "opcode.go: не найден OpHalt")
		os.Exit(1)
	}
	j := strings.Index(src[i:], "\n)\n")
	if j < 0 {
		fmt.Fprintln(os.Stderr, "opcode.go: не найден конец блока const")
		os.Exit(1)
	}
	block := src[i : i+j]
	re := regexp.MustCompile(`(?m)^\s*(Op\w+)(?:\s+Opcode\s*=\s*iota)?\s*//\s*(.*)$`)
	var idents, names []string
	for _, m := range re.FindAllStringSubmatch(block, -1) {
		ident, comment := m[1], strings.TrimSpace(m[2])
		name := ident[2:]
		if comment != "" {
			name = strings.Fields(comment)[0]
		}
		idents = append(idents, ident)
		names = append(names, name)
	}
	var nameStr strings.Builder
	index := []int{0}
	for _, n := range names {
		nameStr.WriteString(n)
		index = append(index, nameStr.Len())
	}
	var val strings.Builder
	for k, id := range idents {
		fmt.Fprintf(&val, "\t_ = x[%s-%d]\n", id, k)
	}
	idx := make([]string, len(index))
	for k, v := range index {
		idx[k] = fmt.Sprint(v)
	}
	out := fmt.Sprintf(`// Code generated by gen_opcode_string.go; DO NOT EDIT.

package vm

import "strconv"

func _() {
	// An "invalid array index" compiler error signifies that the constant values have changed.
	// Re-run "go generate" to regenerate this file.
	var x [1]struct{}
%s}

const _Opcode_name = %q

var _Opcode_index = [...]uint16{%s}

func (i Opcode) String() string {
	idx := int(i) - 0
	if i < 0 || idx >= len(_Opcode_index)-1 {
		return "Opcode(" + strconv.FormatInt(int64(i), 10) + ")"
	}
	return _Opcode_name[_Opcode_index[idx]:_Opcode_index[idx+1]]
}
`, val.String(), nameStr.String(), strings.Join(idx, ", "))
	if err := os.WriteFile("opcode_string.go", []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
